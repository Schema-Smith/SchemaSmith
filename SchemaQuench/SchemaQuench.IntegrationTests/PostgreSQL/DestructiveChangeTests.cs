    protected override string MainDb => FixtureSetup.MainDb;
    protected override string MainConnectionString => TestConnection("postgres");
    protected override string ConfigPrefix => "PostgreSQL";
    protected override string ProductName => "DestructiveChangeProduct";

    protected override string TableJson(string table, params string[] columns) => $$"""
        { "Schema": "public", "Name": "{{table}}",
          "Columns": [ { "Name": "id", "DataType": "integer", "Nullable": false, "Generated": "GENERATED BY DEFAULT AS IDENTITY" }{{string.Concat(columns.Select(c => $", {{ \"Name\": \"{c}\", \"DataType\": \"integer\", \"Nullable\": true }}"))}} ],
          "Indexes": [ { "Name": "pk_{{table}}", "PrimaryKey": true, "Unique": true, "IndexColumns": "id" } ] }
        """;
    protected override string TableFileName(string table) => $"public.{table}.json";
    protected override string Qualified(string table) => $"public.{table}";
    // ANALYZE so reltuples knows the row; a table never analyzed reports its rows as unknown.
    protected override string Insert(string table, string column, int value) => $"INSERT INTO public.{table} ({column}) VALUES ({value}); ANALYZE public.{table}";
