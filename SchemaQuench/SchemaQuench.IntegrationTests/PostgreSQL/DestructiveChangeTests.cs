    protected override long SumOf(string table, string column) => Convert.ToInt64(Scalar($"SELECT SUM({column}) FROM public.{table}"));
    protected override long RowCount(string table) => Count($"SELECT COUNT(*) FROM public.{table}");

    // The rows a column drop on a partitioned table takes are every leaf's, at any depth.
    [Test]
    public void AColumnDropOnASubPartitionedTable_CountsTheRowsInEveryLeaf()
    {
        const string part = "dc_part";
        string Json(string extra) => $$"""
            { "Schema": "public", "Name": "{{part}}",
              "Columns": [ { "Name": "id", "DataType": "integer", "Nullable": false }, { "Name": "k", "DataType": "integer", "Nullable": false }{{extra}} ],
              "Indexes": [ { "Name": "pk_{{part}}", "PrimaryKey": true, "Unique": true, "IndexColumns": "id,k" } ],
              "Partitioning": { "Method": "RANGE", "Expression": "id", "Partitions": [
                  { "Name": "{{part}}_p1", "Bound": "FOR VALUES FROM (0) TO (100)",
                    "Partitioning": { "Method": "LIST", "Expression": "k", "Partitions": [ { "Name": "{{part}}_p1a", "Bound": "DEFAULT" } ] } },
                  { "Name": "{{part}}_p2", "Bound": "FOR VALUES FROM (100) TO (200)" } ] } }
            """;
        Exec($"DROP TABLE IF EXISTS public.{part} CASCADE");
        try
        {
            WritePackage("");
            WriteFile("Tables", $"public.{part}.json", Json(", { \"Name\": \"b\", \"DataType\": \"integer\", \"Nullable\": true }"));
            Deploy();
            Exec($"INSERT INTO public.{part} (id, k, b) VALUES (1, 1, 1), (2, 2, 2), (150, 1, 3); ANALYZE public.{part}");

            WriteFile("Tables", $"public.{part}.json", Json(""));
            var result = Deploy(settings: new System.Collections.Generic.Dictionary<string, string> { ["Target:DestructiveChangePolicy"] = "warn" });

            Assert.That(result.Audit.Single(r => r.Action == "destructive" && r.ObjectName == $"public.{part}.b").EstimatedRows, Is.EqualTo(3));
        }
        finally
        {
            Exec($"DROP TABLE IF EXISTS public.{part} CASCADE");
        }
    }

    // H3 slice B: a type change that loses values silently, and a plain column replaced by a generated one.

    private const string Typed = "dc_typed";

    private void DeployTyped(string type, string value)
    {
        Exec($"DROP TABLE IF EXISTS public.{Typed}");
        WritePackage("");
        WriteFile("Tables", $"public.{Typed}.json", TypedJson(type));
        Deploy();
        Exec($"INSERT INTO public.{Typed} (v) VALUES ({value})");
    }

    private static string TypedJson(string type, string extra = "") => $$"""
        { "Schema": "public", "Name": "{{Typed}}",
          "Columns": [ { "Name": "id", "DataType": "integer", "Nullable": false, "Generated": "GENERATED BY DEFAULT AS IDENTITY" },
                       { "Name": "v", "DataType": "{{type}}", "Nullable": true{{extra}} } ],
          "Indexes": [ { "Name": "pk_{{Typed}}", "PrimaryKey": true, "Unique": true, "IndexColumns": "id" } ] }
        """;

    private string ValueOfV() => Scalar($"SELECT v::text FROM public.{Typed}")?.ToString();

    private static System.Collections.Generic.Dictionary<string, string> Fail => new() { ["Target:DestructiveChangePolicy"] = "fail" };

    [TestCase("numeric(18,4)", "1.2345", "numeric(18,2)")]
    [TestCase("timestamp(6)", "'2020-01-01 10:00:00.123456'", "date")]
    [TestCase("double precision", "1.75", "integer")]
    [TestCase("json", "'{\"a\":1,\"a\":2}'", "jsonb")]
    public void UnderFail_ATypeChangeThatLosesValuesIsRefusedAndTheValueKept(string from, string value, string to)
    {
        DeployTyped(from, value);
        var before = ValueOfV();
        WriteFile("Tables", $"public.{Typed}.json", TypedJson(to));
        try
        {
            var result = Deploy(expectSuccess: false, settings: Fail);
            Assert.Multiple(() =>
            {
                Assert.That(result.Failure?.Error, Does.Contain($"public.{Typed}.v").And.Contain("without an error"), result.Failure?.Error);
                Assert.That(ValueOfV(), Is.EqualTo(before), "the value is untouched");
            });
        }
        finally
        {
            Exec($"DROP TABLE IF EXISTS public.{Typed}");
        }
    }

    [TestCase("integer", "5", "bigint")]
    [TestCase("varchar(10)", "'abc'", "varchar(50)")]
    [TestCase("numeric(10,2)", "1.25", "numeric(12,2)")]
    [TestCase("varchar(10)", "'abc'", "text")]
    public void UnderFail_AWideningTypeChangeGoesAhead(string from, string value, string to)
    {
        DeployTyped(from, value);
        WriteFile("Tables", $"public.{Typed}.json", TypedJson(to));
        try
        {
            var result = Deploy(settings: Fail);
            Assert.That(result.Audit.Where(r => r.Action == "destructive"), Is.Empty);
        }
        finally
        {
            Exec($"DROP TABLE IF EXISTS public.{Typed}");
        }
    }

    [Test]
    public void UnderFail_APlainColumnReplacedByAGeneratedOneIsRefused()
    {
        DeployTyped("integer", "41");
        WriteFile("Tables", $"public.{Typed}.json", TypedJson("integer", ", \"GenerationExpression\": \"id + 1\""));
        try
        {
            var result = Deploy(expectSuccess: false, settings: Fail);
            Assert.Multiple(() =>
            {
                Assert.That(result.Failure?.Error, Does.Contain($"public.{Typed}.v").And.Contain("replaced"), result.Failure?.Error);
                Assert.That(ValueOfV(), Is.EqualTo("41"), "the stored value is kept");
            });
        }
        finally
        {
            Exec($"DROP TABLE IF EXISTS public.{Typed}");
        }
    }

    // The classifier itself, against what PostgreSQL was seen to do with data that does not fit (H3 P2, 17). The live side is
    // spelled as the catalog spells it (int4, float8, bpchar), the declared side as a package does.
    [TestCase("numeric(18,4)", "numeric(18,2)", "loses")]
    [TestCase("numeric(18,2)", "numeric(10,2)", "fails")]
    [TestCase("numeric(18,2)", "numeric(20,4)", "none")]
    [TestCase("numeric(10,2)", "integer", "loses")]
    [TestCase("numeric", "numeric(10,2)", "loses")]
    [TestCase("timestamp(6)", "timestamp(0)", "loses")]
    [TestCase("timestamp", "date", "loses")]
    [TestCase("timestamptz", "timestamp without time zone", "loses")]
    [TestCase("timestamp", "timestamp with time zone", "none")]
    [TestCase("date", "timestamp", "none")]
    [TestCase("time(6)", "time(0)", "loses")]
    [TestCase("interval", "interval second(0)", "loses")]
    [TestCase("float8", "integer", "loses")]
    [TestCase("float8", "real", "loses")]
    [TestCase("float4", "double precision", "none")]
    [TestCase("int4", "bigint", "none")]
    [TestCase("int8", "integer", "fails")]
    [TestCase("int4", "numeric(10,2)", "fails")]
    [TestCase("int4", "numeric(12,2)", "none")]
    [TestCase("int8", "double precision", "loses")]
    [TestCase("int4", "real", "loses")]
    [TestCase("int4", "varchar(2)", "fails")]
    [TestCase("int4", "text", "none")]
    [TestCase("varchar(10)", "varchar(5)", "fails")]
    [TestCase("varchar(10)", "character varying(20)", "none")]
    [TestCase("CHAR(10)", "varchar(10)", "none")]
    [TestCase("text", "varchar(5)", "fails")]
    [TestCase("varchar(10)", "text", "none")]
    [TestCase("text", "integer", "fails")]
    [TestCase("boolean", "integer", "fails")]
    [TestCase("json", "jsonb", "loses")]
    [TestCase("jsonb", "json", "none")]
    [TestCase("varchar(10)", "varchar(10) COLLATE \"C\"", "none")]
    [TestCase("geometry(Point,4326)", "geometry(LineString,4326)", "fails")]
    // A type named with its schema is that type, not the schema: two domains in one schema are different types.
    [TestCase("public.d_amount2", "public.d_amount0", "loses")]
    [TestCase("public.d_amount2", "public.d_amount2", "none")]
    [TestCase("pg_catalog.int4", "integer", "none")]
    public void TheClassifierMatchesWhatTheEngineDoes(string from, string to, string expected)
    {
        Assert.That(Scalar($"SELECT \"SchemaSmith\".\"ColumnChangeLoss\"('{from}', '{to.Replace("'", "''")}')")?.ToString(), Is.EqualTo(expected));
    }
